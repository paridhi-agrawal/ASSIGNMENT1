def safe_ratio(a, b):
    if b == 0 or pd.isna(a) or pd.isna(b):
        return np.nan
    return a / b

def group_rates(frame, threshold):
    pred = (frame["p"] >= threshold).astype(int)
    y = frame["y"].to_numpy()
    pred = pred.to_numpy()
    tp = np.sum((y == 1) & (pred == 1))
    fn = np.sum((y == 1) & (pred == 0))
    fp = np.sum((y == 0) & (pred == 1))
    tn = np.sum((y == 0) & (pred == 0))
    tpr = tp / (tp + fn) if (tp + fn) else np.nan
    fpr = fp / (fp + tn) if (fp + tn) else np.nan
    positive_rate = pred.mean() if len(pred) else np.nan
    ppv = tp / (tp + fp) if (tp + fp) else np.nan
    return positive_rate, tpr, fpr, ppv

